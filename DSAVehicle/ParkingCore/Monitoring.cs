namespace DSAVehicle.ParkingCore;

public class ResolveInput
{
    [StringLength(500)] public string? Note { get; set; }
    public bool FalseAlarm { get; set; }
}

// Alert lifecycle (GC-25): Open → Acknowledged (who/when) → Resolved (note required) or FalseAlarm (needs MarkFalseAlarm).
public static class AlertLifecycle
{
    public static void Acknowledge(ParkingAlert alert, string actor, DateTime now)
    {
        if (alert.Status != "Open") throw new InvalidOperationException("Only open alerts can be acknowledged.");
        alert.Status = "Acknowledged"; alert.AcknowledgedBy = actor; alert.AcknowledgedUtc = now;
    }
    public static void Resolve(ParkingAlert alert, string actor, DateTime now, string? note, bool falseAlarm, bool mayMarkFalseAlarm)
    {
        if (alert.Resolved) throw new InvalidOperationException("The alert is already closed.");
        if (string.IsNullOrWhiteSpace(note) || note.Trim().Length < 3) throw new InvalidOperationException("Write what was done (at least 3 characters) to close the alert.");
        if (falseAlarm && !mayMarkFalseAlarm) throw new InvalidOperationException("Marking a false alarm needs the MarkFalseAlarm permission.");
        if (alert.Status == "Open") { alert.AcknowledgedBy = actor; alert.AcknowledgedUtc = now; }
        alert.Status = falseAlarm ? "FalseAlarm" : "Resolved"; alert.Resolved = true; alert.ResolvedBy = actor; alert.ResolvedUtc = now; alert.ResolutionNote = note.Trim();
    }
    // Closed by the system itself when the condition clears (e.g. camera recording again).
    public static void AutoResolve(ParkingAlert alert, string actor, string note)
    {
        alert.Status = "Resolved"; alert.Resolved = true; alert.ResolvedBy = actor; alert.ResolvedUtc = DateTime.UtcNow; alert.ResolutionNote = note;
    }
}

// Live video wall (GC-29). Browsers can't play RTSP, so a stream gateway (MediaMTX) on the station converts RTSP → WebRTC without re-encoding.
// Each camera is published under its ID; the wall embeds <gateway>/<cameraId>/.
[ApiController, Route("api/v1/parking/video"), Authorize(Policy = Perm.ViewEvidence)]
public class WallController(ParkingDb db, IConfiguration config, AreaScope scope, IDataProtectionProvider protection) : ControllerBase
{
    [HttpGet("wall")]
    public async Task<object> Wall()
    {
        var allowed = await scope.Lanes();
        var lanes = await db.Lanes.AsNoTracking().ToListAsync();
        var locations = await db.Locations.AsNoTracking().ToListAsync();
        var areas = await db.Areas.AsNoTracking().ToListAsync();
        var cameras = (await db.Cameras.AsNoTracking().Where(c => c.Enabled && (c.SourceProtected != "" || c.WallSourceProtected != null)).OrderBy(c => c.Id).ToListAsync())
            .Where(c => allowed is null || (c.LaneId is not null && allowed.Contains(c.LaneId))).ToList();
        string AreaOf(Camera c)
        {
            var lane = lanes.FirstOrDefault(l => l.Id == c.LaneId);
            var location = locations.FirstOrDefault(l => l.Id == lane?.LocationId);
            return areas.FirstOrDefault(a => a.Id == location?.AreaId)?.Name ?? "No area";
        }
        return new {
            gatewayUrl = config["Video:GatewayUrl"],
            groups = cameras.GroupBy(AreaOf).OrderBy(g => g.Key).Select(g => new { area = g.Key, cameras = g.Select(c => new { c.Id, c.Name, c.LaneId,
                recording = c.LastSegmentUtc > DateTime.UtcNow.AddMinutes(-3), lastSegmentUtc = c.LastSegmentUtc, lastMessageUtc = c.LastMessageUtc }) })
        };
    }

    // MediaMTX configuration with the (decrypted) stream sources. Contains camera passwords: Admin only, audited, never cached.
    [HttpGet("gateway-config"), Authorize(Policy = Perm.AdminOnly)]
    public async Task<IActionResult> GatewayConfig()
    {
        var protector = protection.CreateProtector(CameraProtection.Purpose);
        var text = new StringBuilder("# Generated by the parking app. Contains camera credentials: keep it on the station only.\nwebrtc: yes\nhls: no\nrtmp: no\nsrt: no\npaths:\n");
        foreach (var camera in await db.Cameras.AsNoTracking().Where(c => c.Enabled).OrderBy(c => c.Id).ToListAsync())
        {
            var source = camera.WallSourceProtected ?? (camera.SourceProtected.Length > 0 ? camera.SourceProtected : null);
            if (source is null) continue;
            string url;
            try { url = protector.Unprotect(source); } catch (System.Security.Cryptography.CryptographicException) { continue; }
            // Pull the stream only while someone is watching; TCP for reliability on the plant network.
            text.Append($"  {camera.Id}:\n    source: \"{url.Replace("\"", "")}\"\n    sourceOnDemand: yes\n    rtspTransport: tcp\n");
        }
        db.Log(User.Identity?.Name ?? "unknown", "ExportGatewayConfig", "mediamtx.yml"); await db.SaveChangesAsync();
        Response.Headers.CacheControl = "no-store";
        return File(Encoding.UTF8.GetBytes(text.ToString()), "text/yaml", "mediamtx.yml");
    }
}
